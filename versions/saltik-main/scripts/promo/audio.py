"""Original trailer score and event-synchronised synthetic combat design."""
import numpy as np
from scipy.signal import butter,sosfilt
import wave,json
from pathlib import Path
RATE=48000;DURATION=20
work=Path('/workspace/recovery-saltik/promo');rng=np.random.default_rng(41027)
mix=np.zeros((RATE*DURATION,2))
def add(signal,at,gain=1,pan=0):
 start=round(at*RATE);n=min(len(signal),len(mix)-start)
 if n<=0 or start<0:return
 mix[start:start+n,0]+=signal[:n]*gain*np.sqrt((1-pan)/2)
 mix[start:start+n,1]+=signal[:n]*gain*np.sqrt((1+pan)/2)
def tone(freq,duration,decay=3):
 t=np.arange(round(duration*RATE))/RATE
 return np.sin(2*np.pi*freq*t)*np.minimum(1,t/.012)*np.exp(-t*decay)
def noise(duration,cutoff=1700):
 x=rng.normal(0,1,round(duration*RATE));return sosfilt(butter(2,cutoff,fs=RATE,output='sos'),x)
def impact(at,gain=.6):
 t=np.arange(round(1.25*RATE))/RATE
 kick=np.sin(2*np.pi*(34*t+19*(1-np.exp(-t*18))/18))*np.exp(-t*6)
 boom=noise(1.25,400)*np.exp(-t*4)*.8
 add(kick+boom,at,gain)
def kick(at,gain):
 t=np.arange(round(.35*RATE))/RATE
 add(np.sin(2*np.pi*(45*t+90*(1-np.exp(-t*32))/32))*np.exp(-t*19),at,gain)
def snare(at,gain):
 t=np.arange(round(.22*RATE))/RATE
 s=rng.normal(0,1,len(t));s=s-sosfilt(butter(2,1000,fs=RATE,output='sos'),s)
 add((s*.38+np.sin(2*np.pi*185*t)*.25)*np.exp(-t*26),at,gain)
# A low, unresolved pulse opens into a 140 BPM chase.
for at in [0,.65,1.3]:kick(at,.34)
for at in np.arange(2.2,16.95,60/140):
 intensity=.32+.20*min(1,(at-2.2)/8)
 kick(at,intensity)
 snare(at+60/280,intensity*.70)
 for offset in [0,60/560]:
  t=np.arange(round(.045*RATE))/RATE
  add(rng.normal(0,1,len(t))*np.exp(-t*110),at+offset,.035,(-1 if round(at*10)%2 else 1)*.65)
notes=[73.416,73.416,87.307,110,73.416,130.813,110,87.307]
for i,at in enumerate(np.arange(2.2,16.9,60/280)):
 t=np.arange(round(.20*RATE))/RATE;f=notes[i%8]
 synth=sum(np.sin(2*np.pi*f*h*t)/h for h in range(1,7))
 synth*=np.minimum(1,t/.008)*np.exp(-t*19)
 add(synth,at,.11+at*.003,np.sin(i*.8)*.35)
 add(synth,at+.13,.025,-np.sin(i*.8)*.5)
# Sustained minor brass/strings and restrained upper harmonics.
for at,root in [(0,36.708),(4.6,43.654),(7.3,36.708),(10.9,48.999),(12.7,36.708)]:
 length=min(4.3,17-at);t=np.arange(round(length*RATE))/RATE
 env=np.minimum(1,t/.7)*np.minimum(1,(length-t)/.8)
 chord=np.zeros(len(t))
 for ratio in [1,2,2**(3/12),2**(7/12)]:
  f=root*ratio
  chord+=sum(np.sin(2*np.pi*f*h*t+np.sin(t*.7)*.02)/h**1.3 for h in range(1,7))*.17
 add(chord*env,at,.34)
for at,length in [(3.55,1.05),(9.9,1),(14.85,2.15)]:
 t=np.arange(round(length*RATE))/RATE;u=t/length
 sweep=noise(length,4500)*u**2
 rise=np.sin(2*np.pi*(180*t+520*t*t/length))*u**2
 add(sweep*.30+rise*.10,at,.35)
for at in [0,2.2,4.6,7.3,9.3,10.9,12.7,14.3,15.8,17]:impact(at,.40 if at<17 else .9)
# Title resolves to a wide heroic chord; let the final hit breathe.
t=np.arange(3*RATE)/RATE
for j,f in enumerate([73.416,146.832,184.997,220,293.665]):
 add(np.sin(2*np.pi*f*t)*np.exp(-t*.9)*np.minimum(1,t/.015),17,.23,(-.4+j*.2))
# These timestamps are generated by the actual simulation used in the edit.
evidence=json.loads((work/'evidence.json').read_text())
last={}
for e in evidence['events']:
 at=e['at'];kind=e['type']
 if at>=17 or at-last.get(kind,-10)<(.16 if kind=='shot' else .28):continue
 last[kind]=at
 if kind in ['shot','enemyshot']:
  t=np.arange(round(.06*RATE))/RATE
  add((rng.normal(0,1,len(t))*.18+np.sin(2*np.pi*760*t)*.35)*np.exp(-t*70),at,.17)
 elif kind in ['explosion','cluster','breach-shot','duel-impact']:impact(at,.20)
 elif kind in ['missile','homing']:
  t=np.arange(round(.34*RATE))/RATE;add(noise(.34,2400)*np.exp(-t*10),at,.28)
# Soft saturation and a clean final fade prevent sample clipping/cutoff clicks.
mix=np.tanh(mix*.85)
fade=np.minimum(1,np.arange(len(mix))/(RATE*.025))*np.minimum(1,(len(mix)-1-np.arange(len(mix)))/(RATE*.22))
mix*=fade[:,None]
with wave.open(str(work/'original-score.wav'),'wb') as f:
 f.setnchannels(2);f.setsampwidth(2);f.setframerate(RATE);f.writeframes((mix*30000).astype('<i2').tobytes())
print('Original 20-second score rendered; peak',float(np.max(np.abs(mix))))
